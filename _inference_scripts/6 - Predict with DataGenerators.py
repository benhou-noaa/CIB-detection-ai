def rgb_to_bgr(image):
    "converts input image from rgb to bgr channel order"
    image = np.array(image)
    image = cv2.cvtColor(image, cv2.COLOR_RGB2BGR)
    
    return image

def bgr_to_rgb(image):
    image = np.array(image)
    image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
    
    return image

