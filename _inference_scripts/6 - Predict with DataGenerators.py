def perform_inference(friendly_name, model_architecture_json, model_weights_h5, spec_generator_obj):
    print('\nloading {}'.format(friendly_name))
    with open(os.path.join(model_dir, "-".join([model_name,model_architecture_json])), 'r') as f:
        model = model_from_json(f.read())
    model.load_weights(os.path.join(model_dir,"-".join([model_name, model_weights_h5])))
    print("done loading {}".format(friendly_name))
    
    predict_start_time = datetime.datetime.now()
    print("\npredicting with {}".format(friendly_name), predict_start_time)
    model_prediction = model.predict(spec_generator_obj, verbose=1)
    #model_cnn_prediction = model_cnn.predict_generator(spectrogram_generator, verbose=1)
    elasped = datetime.datetime.now() - predict_start_time
    
    print('done, took {} minutes'.format(str(elasped.total_seconds()/60)))
    print('unloading {}'.format(friendly_name))
    
    del model
    gc.collect()
    tf.keras.backend.clear_session()
    
    return model_prediction

